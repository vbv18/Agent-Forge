import { PDFDocument } from "pdfkit";

export default async function generatePDF(data) {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: "A4",
        margin: 50,
        info: {
          Author: "AgentForge",
          Title: data.title,
          Creator: "AgentForge",
        },
      });

      const chunks = [];
      doc.on("data", (chunk) => chunks.push(chunk));
      doc.on("end", () =>
        // {
        resolve(Buffer.concat(chunks))
        // }
      );

      doc.on("error", reject);

      // title
      doc
        .fontSize(28)
        .text(data.title, {
          align: "center",
        })
        .fillColor("#111827");

      // subtitle
      if (data.subtitle) {
        doc.moveDown(0.5);

        doc
          .fontSize(12)
          .text(data.subtitle, {
            align: "center",
          })
          .fillColor("#6B7280");
      }

      doc.moveDown(2);

      // sections
      data?.sections?.forEach((section) => {
        doc
          .fontSize(18)
          .text(section.heading, {
            align: "left",
          })
          .fillColor("#111827");

        doc.moveDown(0.5);

        section?.points?.forEach((point) => {
          doc
            .fontSize(12)
            .text(`• ${point}`, {
              align: "left",
              lineGap: 5,
            })
            .fillColor("#6B7280");
        });

        doc.moveDown(1);
      });

      // Footer
      doc.moveDown(1);

      doc
        .fontSize(10)
        .text("Generated By AgentForge", {
          align: "center",
        })
        .fillColor("#6B7280");

      // Finalize PDF
      doc.end();
    } catch (error) {
      reject(error);
    }
  });
}
